def render_bigtext(text):
    """Join big letters into 5-row block text."""
    rows = ["", "", "", "", ""]
    for ch in text:
        glyph = LETTERS.get(ch.upper(), LETTERS[" "])
        for i in range(5):
            rows[i] += glyph[i] + " "
    return rows

